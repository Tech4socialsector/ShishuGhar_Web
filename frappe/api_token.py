"""Lifecycle (expiry and revocation) of the API key / secret pair handed to the mobile app.

Why this exists
---------------
``frappe.val.api.login`` issues ``api_key`` + ``api_secret`` to the mobile app, which then
sends ``Authorization: token <key>:<secret>`` with every request. Those credentials used to
live forever and there was no way to take them back.

* **Expiry.** ``User.api_token_expires_on`` is stamped at every mobile login
  (``app_token_expiry_days`` in site_config.json, default ``DEFAULT_EXPIRY_DAYS``; ``0``
  means "never expire"). After that moment the key/secret stop working and the app has to
  log in again. A ``NULL`` expiry means "no expiry": that is how API keys generated by hand
  for server-to-server integrations behave, so they are untouched.
* **Revocation.** ``revoke(user)`` deletes the stored secret and the expiry. It runs when
  the user changes their password, can be triggered by the user (``revoke_app_token``) or
  by a System Manager for any user, and ``revoke_all()`` rotates every mobile token at once
  (``bench --site <site> execute frappe.api_token.revoke_all``).
* A *disabled* user can no longer authenticate with an API key either.

Kept free of any request / session state so it can be unit tested with a stubbed frappe.
"""

import frappe
from frappe import _
from frappe.utils import add_to_date, cint, get_datetime, now_datetime
from frappe.utils.password import remove_encrypted_password

EXPIRY_FIELD = "api_token_expires_on"
DEFAULT_EXPIRY_DAYS = 30


def expiry_days() -> int:
	value = frappe.conf.get("app_token_expiry_days")
	return DEFAULT_EXPIRY_DAYS if value is None else max(cint(value), 0)


def new_expiry():
	"""Expiry timestamp for a token issued now (``None`` when expiry is switched off)."""
	days = expiry_days()
	return add_to_date(now_datetime(), days=days) if days else None


def _has_expiry_column() -> bool:
	# Guard: a deploy that has not been migrated yet must not lock everybody out.
	return frappe.db.has_column("User", EXPIRY_FIELD)


def token_usable(user) -> bool:
	"""True when ``user`` is enabled and their app token has not expired."""
	fields = ["enabled"] + ([EXPIRY_FIELD] if _has_expiry_column() else [])
	row = frappe.db.get_value("User", user, fields, as_dict=True)
	if not row or not cint(row.get("enabled")):
		return False

	expires_on = row.get(EXPIRY_FIELD)
	return not (expires_on and get_datetime(expires_on) <= now_datetime())


def assert_token_usable(user) -> None:
	"""Raise ``AuthenticationError`` if the key/secret of ``user`` must no longer be accepted."""
	if not token_usable(user):
		frappe.throw(_("Your API token has expired or been revoked. Please log in again."), frappe.AuthenticationError)


def revoke(user, only_app_issued=False) -> None:
	"""Invalidate the key/secret issued to ``user`` (the next mobile login issues a new one).

	``only_app_issued=True`` leaves hand-made integration keys (no expiry) alone; automatic
	triggers such as a password change use it so a server-to-server integration is not cut off.
	"""
	if only_app_issued:
		if not _has_expiry_column() or not frappe.db.get_value("User", user, EXPIRY_FIELD):
			return
	remove_encrypted_password("User", user, "api_secret")
	if _has_expiry_column():
		frappe.db.set_value("User", user, EXPIRY_FIELD, None, update_modified=False)
	frappe.clear_document_cache("User", user)


def revoke_all() -> int:
	"""Revoke every token that carries an expiry, i.e. every one issued by the mobile login.

	Hand-made integration keys have no expiry and are left alone. Returns the number of users.
	"""
	if not _has_expiry_column():
		return 0
	users = frappe.get_all("User", filters={EXPIRY_FIELD: ("is", "set")}, pluck="name")
	for user in users:
		revoke(user)
	frappe.db.commit()
	return len(users)
